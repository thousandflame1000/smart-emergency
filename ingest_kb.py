def run():
    print("開始載入知識庫...")
    total = 0
    for doc in DOCUMENTS:
        n = ingest_document(
            content  = doc["content"],
            source   = doc["source"],
            category = doc["category"],
        )
        print(f"  [{doc['category']}] {doc['source'][:30]}... → {n} chunks")
        total += n

    print(f"\n✅ 知識庫載入完成！共 {total} 個 chunks")
    return total


if __name__ == "__main__":
    run()
